import {isMainThread, parentPort, threadId, workerData} from 'node:worker_threads';

import type {AgentRunResult} from "@cline/agents";

import {QAAgent} from './agent.ts';
import {Joinery} from '../join.ts';
import type {KnownEventFromType} from "@slack/bolt";
import type {GenericMessageEvent} from "@slack/web-api";
import {ScratchStorage} from "../common/scratch-storage.ts";

if (isMainThread) {
    console.error('thread.ts running on main thread, exiting')
    process.exit(1);
}

const storage = new ScratchStorage(workerData.storagePath, `worker-${workerData.key}`);

class ChatterImpl {
    private readonly j = new Joinery();
    private readonly _slack = this.j.m<any>();
    private readonly _agentDone = this.j.m<{agent: QAAgent, result: AgentRunResult}>();
    private readonly _agentIdle = this.j.m<QAAgent>();
    private readonly _notify = this.j.m<string>();
    private readonly _pendingNotifications = this.j.m<string[]>();
    private readonly _noPendingNotifications = this.j.m<void>();
    private readonly _state = this.j.m<{messageCount: number}>();

    constructor() {
        this.j.on([this._notify, this._noPendingNotifications], async (message) => {
            this._pendingNotifications([message]);
        });

        this.j.on([this._notify, this._pendingNotifications], async (message, messages) => {
            this._pendingNotifications([...messages, message]);
        });

        this.j.on([this._agentIdle, this._pendingNotifications], async (agent, messages) => {
            this._noPendingNotifications();
            this._agentDone({
                agent,
                result: await agent.process(`Notifications:\n${messages.join('\n')}\n\nThese were generated by tools. The humans cannot see these unless you want to tell them. If you send a reply, it will be send to humans; if you don't want to bother the humans, just reply with GOTCHA`),
            })
        });

        // TODO: This serializes user messages, we can buffer instead.
        this.j.on([this._slack, this._agentIdle, this._state], async (event, agent, {messageCount}) => {
            console.log('slack+agent-idle');
            this._state({messageCount: messageCount + 1});

            // Remind the user how to make us go away, sometimes.
            if ([1, 2].indexOf(messageCount % 5) !== -1) {
                parentPort.postMessage({
                    type: 'setStatus',
                    status: {
                        status: 'processing',
                        loading_messages: [
                            messageCount % 5 === 1 ?
                                'Tip: Use @AutoQA bye, and I\'ll butt out. 👋'
                                : 'Tip: Mention @AutoQA any time and I\'ll pop in.'
                        ]
                    }
                });
            }

            // Send the message to the agent.
            this._agentDone({
                agent,
                result: await agent.process(this.slackToAgentMessageText(event))
            });
        });

        this.j.on([this._agentDone], ({agent, result}) => {
            console.log('agent-done')
            this._agentIdle(agent);
            console.log(`worker ${threadId}: ${JSON.stringify(result, null, 2)}`);
            this.agentMessageToSlack(result);
        });

        const agent = new QAAgent(storage, this._notify, {
            uploadFile(filename: string): void {
                console.log(`W->M upload-file ${filename}`);
                parentPort.postMessage({
                    type: 'upload-file',
                    filename,
                });
            }
        });
        agent.start().then(() => this._agentIdle(agent));
        this._state({messageCount: 0});
        this._noPendingNotifications();
    }

    get slack() { return this._slack; }

    private slackToAgentMessageText(event: KnownEventFromType<'message'>): string {
        const messageEvent = event as GenericMessageEvent;
        return `${messageEvent.user} said:\n\n${messageEvent.text}`
    }

    private agentMessageToSlack(result: AgentRunResult): void {
        switch (result.status) {
            case 'completed': {
                if (result.outputText === 'GOTCHA') {
                    // This is our safe word when the agent wants to respond, but does not want to wake humans.
                    break;
                }
                parentPort.postMessage({
                    type: 'say',
                    text: result.outputText,
                });
                break;
            }
            default: {
                parentPort.postMessage({
                    type: 'say',
                    text: `Something went wrong :sadge:
\`\`\`json
${JSON.stringify(result, null, 2)}
\`\`\``
                })
                break;
            }
        }
    }
}

const chatter = new ChatterImpl();

parentPort.on('message', async (event) => {
    console.log(`W->M ${JSON.stringify(event, null, 2)}`);
    if ('type' in event) {
        if (event.type === 'slack') {
            chatter.slack(event.event);
        }
    }
})
